object AppLanguageProvider {
    fun getStrings(languageCode: String): AppStrings {
        val resolvedCode = if (languageCode == "system" || languageCode.isBlank()) {
            val deviceLang = Locale.getDefault().language.lowercase()
            when {
                deviceLang.startsWith("in") || deviceLang.startsWith("id") -> "in"
                deviceLang.startsWith("ja") -> "ja"
                deviceLang.startsWith("ko") -> "ko"
                deviceLang.startsWith("ru") -> "ru"
                deviceLang.startsWith("es") -> "es"
                deviceLang.startsWith("en") -> "en"
                else -> "en" // fallback global
            }
        } else {
            languageCode.lowercase()
        }

        return when {
            resolvedCode.startsWith("in") || resolvedCode.startsWith("id") -> IndonesianStrings
            resolvedCode.startsWith("ja") -> JapaneseStrings
            resolvedCode.startsWith("ko") -> KoreanStrings
            resolvedCode.startsWith("ru") -> RussianStrings
            resolvedCode.startsWith("es") -> SpanishStrings
            resolvedCode.startsWith("en") -> EnglishStrings
            else -> EnglishStrings
        }
    }
}

val LocalAppStrings = staticCompositionLocalOf { IndonesianStrings }
